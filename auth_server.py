DEFAULT_DATABASE = Path(__file__).with_name("tower_defense_accounts.sqlite3")
USERNAME_PATTERN = re.compile(r"^[A-Za-z0-9_]{3,24}$")
_USERNAME_EQUALS_PATTERN = re.compile(r"(?i)\busername\s*=\s*\?")
_ORDER_USERNAME_PATTERN = re.compile(r"(?i)ORDER BY\s+username\s+COLLATE NOCASE")


class DatabaseConnection:
    """Keep the account queries portable between local SQLite and hosted PostgreSQL."""

    def __init__(self, connection: Any, postgres: bool) -> None:
        self.connection = connection
        self.postgres = postgres

    def execute(self, query: str, parameters: tuple[Any, ...] = ()) -> Any:
        if self.postgres:
            query = _USERNAME_EQUALS_PATTERN.sub(
                "LOWER(username) = LOWER(%s)", query
            )
            query = _ORDER_USERNAME_PATTERN.sub("ORDER BY LOWER(username)", query)
            query = query.replace("COLLATE NOCASE", "")
            query = query.replace("MAX(credits, ?)", "GREATEST(credits, %s)")
            query = query.replace("?", "%s")
        return self.connection.execute(query, parameters)

    def commit(self) -> None:
        self.connection.commit()

    def rollback(self) -> None:
        self.connection.rollback()

    def close(self) -> None:
        self.connection.close()


def create_app(
    database_path: str | Path = DEFAULT_DATABASE,
    database_url: str | None = None,
    require_database_url: bool = False,
) -> Flask:
    app = Flask(__name__)
    app.config["DATABASE"] = str(database_path)
    app.config["DATABASE_URL"] = database_url or os.environ.get("DATABASE_URL")
    app.config["REQUIRE_DATABASE_URL"] = require_database_url
    database_ready = False
    database_init_lock = Lock()

    def initialize_database(connection: Any, postgres: bool) -> None:
        if postgres:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS accounts (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username TEXT NOT NULL,
                    password_hash TEXT NOT NULL,
                    is_admin INTEGER NOT NULL DEFAULT 0,
                    custom_speed_access INTEGER NOT NULL DEFAULT 0
                )
                """
            )
            old_columns = {
                row["column_name"]
                for row in connection.execute(
                    """
                    SELECT column_name FROM information_schema.columns
                    WHERE table_schema = current_schema() AND table_name = 'accounts'
                    """
                ).fetchall()
            }
            for column, definition in (
                ("credits", "BIGINT NOT NULL DEFAULT 0"),
                ("unlocked_units", "TEXT NOT NULL DEFAULT '[]'"),
                ("unit_levels", "TEXT NOT NULL DEFAULT '{}'"),
                ("starting_cash", "BIGINT NOT NULL DEFAULT 250"),
                ("unit_copies", "TEXT NOT NULL DEFAULT '{}'"),
                ("unit_traits", "TEXT NOT NULL DEFAULT '{}'"),
                ("trait_options", "TEXT NOT NULL DEFAULT '{}'"),
                ("crates", "TEXT NOT NULL DEFAULT '{}'"),
                ("daily_challenge_date", "TEXT NOT NULL DEFAULT ''"),
                ("story_level", "BIGINT NOT NULL DEFAULT 1"),
                ("equipped_units", "TEXT NOT NULL DEFAULT '[]'"),
                ("battle_pass_xp", "BIGINT NOT NULL DEFAULT 0"),
                ("battle_pass_claimed", "TEXT NOT NULL DEFAULT '[]'"),
            ):
                connection.execute(
                    f"ALTER TABLE accounts ADD COLUMN IF NOT EXISTS {column} {definition}"
                )
            connection.execute(
                "CREATE UNIQUE INDEX IF NOT EXISTS accounts_username_ci ON accounts (LOWER(username))"
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS sessions (
                    token TEXT PRIMARY KEY,
                    account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE
                )
                """
            )
        else:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS accounts (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    username TEXT NOT NULL UNIQUE COLLATE NOCASE,
                    password_hash TEXT NOT NULL,
                    is_admin INTEGER NOT NULL DEFAULT 0,
                    custom_speed_access INTEGER NOT NULL DEFAULT 0
                )
                """
            )
            columns = {
                row["name"]
                for row in connection.execute("PRAGMA table_info(accounts)").fetchall()
            }
            for column, definition in (
                ("credits", "INTEGER NOT NULL DEFAULT 0"),
                ("unlocked_units", "TEXT NOT NULL DEFAULT '[]'"),
                ("unit_levels", "TEXT NOT NULL DEFAULT '{}'"),
                ("starting_cash", "INTEGER NOT NULL DEFAULT 250"),
                ("unit_copies", "TEXT NOT NULL DEFAULT '{}'"),
                ("unit_traits", "TEXT NOT NULL DEFAULT '{}'"),
                ("trait_options", "TEXT NOT NULL DEFAULT '{}'"),
                ("crates", "TEXT NOT NULL DEFAULT '{}'"),
                ("daily_challenge_date", "TEXT NOT NULL DEFAULT ''"),
                ("story_level", "INTEGER NOT NULL DEFAULT 1"),
                ("equipped_units", "TEXT NOT NULL DEFAULT '[]'"),
                ("battle_pass_xp", "INTEGER NOT NULL DEFAULT 0"),
                ("battle_pass_claimed", "TEXT NOT NULL DEFAULT '[]'"),
            ):
                if column not in columns:
                    connection.execute(f"ALTER TABLE accounts ADD COLUMN {column} {definition}")
            old_columns = columns
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS sessions (
                    token TEXT PRIMARY KEY,
                    account_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE
                )
                """
            )

        if "unit_copies" not in old_columns:
            for account in connection.execute(
                "SELECT id, unlocked_units FROM accounts"
            ).fetchall():
                unlocked = json.loads(account["unlocked_units"])
                if STARTER_UNIT_ID not in unlocked:
                    unlocked.append(STARTER_UNIT_ID)
                    DatabaseConnection(connection, postgres).execute(
                        "UPDATE accounts SET unlocked_units = ? WHERE id = ?",
                        (json.dumps(unlocked), account["id"]),
                    )

    def connect_database() -> DatabaseConnection:
        nonlocal database_ready
        url = app.config["DATABASE_URL"]
        if app.config["REQUIRE_DATABASE_URL"] and not url:
            raise RuntimeError(
                "DATABASE_URL is not configured. Connect a PostgreSQL database to this Vercel project."
            )
        postgres = bool(url)
        if postgres:
            connection = psycopg.connect(url, row_factory=dict_row, connect_timeout=8)
        else:
            connection = sqlite3.connect(app.config["DATABASE"])
            connection.row_factory = sqlite3.Row
        wrapped = DatabaseConnection(connection, postgres)
        if not database_ready:
            with database_init_lock:
                if not database_ready:
                    initialize_database(connection, postgres)
                    wrapped.commit()
                    database_ready = True
        return wrapped

    def account_payload(account: Any, token: str) -> dict[str, Any]:
        return {
            "token": token,
            "username": account["username"],
            "is_admin": bool(account["is_admin"]),
            "custom_speed_access": bool(account["custom_speed_access"]),
        }

    def authenticated_account() -> Any | None:
        authorization = request.headers.get("Authorization", "")
        scheme, _, token = authorization.partition(" ")
        if scheme.lower() != "bearer" or not token:
            return None

        connection = connect_database()
        try:
            session = connection.execute(
                "SELECT account_id FROM sessions WHERE token = ?",
                (token,),
            ).fetchone()
            if session is None:
                return None
            return connection.execute(
                "SELECT id, username, is_admin, custom_speed_access FROM accounts WHERE id = ?",
                (session["account_id"],),
            ).fetchone()
        finally:
            connection.close()

    def profile_payload(account_id: int) -> dict[str, Any]:
        connection = connect_database()
        try:
            account = connection.execute(
                """
                SELECT credits, unlocked_units, unit_levels, starting_cash, unit_copies,
                       unit_traits, trait_options, crates, daily_challenge_date, story_level,
                       equipped_units, battle_pass_xp, battle_pass_claimed
                FROM accounts WHERE id = ?
                """,
                (account_id,),
            ).fetchone()
            if account is None:
                raise ValueError("Account profile not found.")
            return {
                "credits": account["credits"],
                "unlocked_units": json.loads(account["unlocked_units"]),
                "unit_levels": json.loads(account["unit_levels"]),
                "starting_cash": account["starting_cash"],
                "unit_copies": json.loads(account["unit_copies"]),
                "unit_traits": json.loads(account["unit_traits"]),
                "trait_options": json.loads(account["trait_options"]),
                "crates": json.loads(account["crates"]),
                "daily_challenge_date": account["daily_challenge_date"],
                "story_level": account["story_level"],
                "equipped_units": json.loads(account["equipped_units"]),
                "battle_pass_xp": account["battle_pass_xp"],
                "battle_pass_claimed": json.loads(account["battle_pass_claimed"]),
            }
        finally:
            connection.close()

    def profile_account_id() -> int | None:
        account = authenticated_account()
        return int(account["id"]) if account is not None else None

